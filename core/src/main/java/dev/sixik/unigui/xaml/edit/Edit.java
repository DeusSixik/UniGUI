package dev.sixik.unigui.xaml.edit;

import dev.sixik.unigui.xaml.schema.Schema;

import java.util.Optional;

/**
 * Обратимая правка документа: команда с {@link #apply()} и {@link #undo()}.
 *
 * <p>Правка хранит ссылки на узлы, а не пути, поэтому остаётся верной при любых других правках между
 * применением и откатом, пока откат выполняется строго в обратном порядке (это гарантирует
 * {@link EditHistory}).</p>
 */
public interface Edit {
    /**
     * @return короткое описание для меню «Отменить …»
     */
    String label();

    /**
     * Проверяет правку до применения. Документ при этом не меняется.
     *
     * @param schema реестр типов для проверки правил вложенности
     * @return описание проблемы, если правку применять нельзя
     */
    default Optional<String> check(Schema schema) {
        return Optional.empty();
    }

    /**
     * Применяет правку. Вызывается один раз; повторное применение после {@link #undo()} допустимо.
     */
    void apply();

    /**
     * Откатывает применённую правку.
     */
    void undo();

    /**
     * Пытается слить следующую, уже применённую правку с этой. Нужно, чтобы перетаскивание ползунка в инспекторе
     * давало один шаг отмены, а не сотню.
     *
     * @param next правка, которая только что применена после этой
     * @return правка, которую следует оставить в истории вместо двух, или {@code null}, если слить нельзя
     */
    default Edit mergeWith(Edit next) {
        return null;
    }
}
