package dev.sixik.unigui.xaml.edit;

/**
 * Событие сессии редактора: панели подписываются на него, чтобы перерисоваться.
 *
 * @param kind что изменилось
 */
public record SessionChange(Kind kind) {
    /** Что изменилось. */
    public enum Kind {
        /** Документ или его текст изменились (правка, отмена, замена текста, возврат). */
        DOCUMENT_CHANGED,
        /** Выбранный узел изменился. */
        SELECTION_CHANGED,
        /** Изменилось число шагов отмены или повтора. */
        UNDO_STACK_CHANGED,
        /** Изменился набор диагностик любого канала. */
        DIAGNOSTICS_CHANGED,
        /** Режим редактора переключён. */
        MODE_CHANGED,
        /** Документ сохранён в источник. */
        SAVED,
        /** Документ возвращён к сохранённому состоянию. */
        REVERTED
    }
}
