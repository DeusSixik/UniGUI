package dev.sixik.unigui.api.math;

/**
 * Чтение единичного кватерниона вращения. Компоненты безразмерны, порядок записи XYZW.
 */
public interface QuatView {
    /**
     * Читает компоненту X векторной части.
     *
     * @return безразмерное значение.
     */
    float x();

    /**
     * Читает компоненту Y векторной части.
     *
     * @return безразмерное значение.
     */
    float y();

    /**
     * Читает компоненту Z векторной части.
     *
     * @return безразмерное значение.
     */
    float z();

    /**
     * Читает скалярную часть.
     *
     * @return безразмерное значение.
     */
    float w();
}
