package dev.sixik.unigui.api.widget;

/**
 * Состояние checkbox-like виджетов.
 *
 * <p>Enum используется не только классическим {@code Checkbox}, но и любыми контролами,
 * которым нужно представить бинарное или частично выбранное состояние. {@link #INDETERMINATE}
 * нужен для древовидных списков, batch-selection и настроек, где дочерние элементы выбраны
 * не полностью.</p>
 */
public enum CheckboxState {
    /** Значение выключено, галочка не отображается. */
    UNCHECKED,

    /** Значение включено, галочка отображается как выбранная. */
    CHECKED,

    /** Значение смешанное: часть дочерних или связанных элементов выбрана. */
    INDETERMINATE
}