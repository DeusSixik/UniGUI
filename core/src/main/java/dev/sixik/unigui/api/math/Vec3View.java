package dev.sixik.unigui.api.math;

/**
 * Чтение трёхкомпонентного вектора. Единицы задаёт система координат вызывающего кода.
 */
public interface Vec3View {
    /**
     * Читает компоненту по оси X.
     *
     * @return компонента в единицах вектора.
     */
    float x();

    /**
     * Читает компоненту по оси Y.
     *
     * @return компонента в единицах вектора.
     */
    float y();

    /**
     * Читает компоненту по оси Z.
     *
     * @return компонента в единицах вектора.
     */
    float z();
}
