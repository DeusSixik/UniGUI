package dev.sixik.unigui.api.style;

/**
 * Форма индикатора направления сортировки в заголовке {@code VirtualTableView}.
 *
 * <p>Индикатор рисуется векторными примитивами {@code DrawScope}, поэтому не зависит от
 * шрифта и от наличия символов {@code ^}/{@code v} в атласе.</p>
 */
public enum TableSortIndicatorStyle {
    /**
     * Контурный шеврон: «крыша» для возрастания и «чаша» для убывания.
     */
    CHEVRON,
    /**
     * Заполненный треугольник, направленный вершиной вверх либо вниз.
     */
    TRIANGLE
}
