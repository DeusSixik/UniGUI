package dev.sixik.unigui.api.layout;

/**
 * Распределяет flex-линии вдоль поперечной оси переносимого контейнера.
 *
 * <p>Аналог CSS {@code align-content}. Применяется, когда контейнер переносит детей на
 * несколько линий; одна линия сохраняет поведение {@code align-items}.</p>
 */
public enum AlignContent {
    /**
     * Растягивает линии на всё доступное место поперечной оси.
     */
    STRETCH,
    /**
     * Упаковывает линии в начале поперечной оси.
     */
    START,
    /**
     * Упаковывает линии по центру поперечной оси.
     */
    CENTER,
    /**
     * Упаковывает линии в конце поперечной оси.
     */
    END,
    /**
     * Распределяет свободное место между линиями, без отступов по краям.
     */
    SPACE_BETWEEN,
    /**
     * Распределяет свободное место вокруг линий, по половине отступа по краям.
     */
    SPACE_AROUND,
    /**
     * Распределяет свободное место равномерно вокруг линий, с полными отступами по краям.
     */
    SPACE_EVENLY
}
