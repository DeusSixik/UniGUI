package dev.sixik.unigui.api.style;

/**
 * Состояние виджета, для которого StylePack может задавать отдельные значения свойств.
 *
 * <p>Состояние выбирается самим виджетом перед чтением style-значений и построением
 * {@code RenderPlan}. Если для состояния нет override, стиль обычно откатывается к
 * {@link #NORMAL}.</p>
 */
public enum WidgetState {
    /** Обычное состояние без активного взаимодействия. */
    NORMAL,
    /** Указатель находится над виджетом. */
    HOVERED,
    /** Виджет нажат или находится в pressed-фазе взаимодействия. */
    PRESSED,
    /** Виджет отключён и не должен реагировать на ввод. */
    DISABLED,
    /** Виджет владеет клавиатурным фокусом. */
    FOCUSED,
    /** Виджет или строка выбраны. */
    SELECTED,
    /** Checked-состояние для checkbox/radio/toggle controls. */
    CHECKED
}