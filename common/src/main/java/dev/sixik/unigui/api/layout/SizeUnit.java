package dev.sixik.unigui.api.layout;

public enum SizeUnit {
    /**
     * Автоматический размер: вычисляется из содержимого или ограничений родителя.
     */
    AUTO,
    /**
     * Фиксированный размер в пикселях.
     */
    PIXELS,
    /**
     * Размер в процентах от доступного размера родителя.
     */
    PERCENT,
    /**
     * Размер по содержимому: вычисляется из измеренного содержимого, см. {@code flex-basis: content}.
     */
    CONTENT,
    /**
     * Минимальный размер содержимого по его внутренней ширине.
     */
    MIN_CONTENT,
    /**
     * Максимальный размер содержимого по его внутренней ширине.
     */
    MAX_CONTENT,
    /**
     * Размер по содержимому, ограниченный пиксельным пределом.
     */
    FIT_CONTENT
}
