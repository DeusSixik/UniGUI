package dev.sixik.unigui.api.layout;

/**
 * Выбирает позиционирование внутри потока компоновки или вне него.
 */
public enum PositionType {
    /**
     * Обычный поток, отступы через insets игнорируются.
     */
    STATIC,
    /**
     * Участвует в обычном потоке, затем сдвигается на {@code left/top}
     * без изменения раскладки соседей.
     */
    RELATIVE,
    /**
     * Позиционируется относительно области содержимого родителя с учётом отступов и размеров.
     */
    ABSOLUTE,
    /**
     * Вне потока как {@code ABSOLUTE} в текущей версии: позиционируется
     * относительно ближайшего хоста, а не вьюпорта. Настоящая привязка
     * к вьюпорту — через overlay-хосты.
     */
    FIXED
}
