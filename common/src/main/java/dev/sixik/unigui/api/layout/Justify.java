package dev.sixik.unigui.api.layout;

public enum Justify {
    /**
     * Выравнивает или размещает значение в начале доступной области.
     */
    START,
    /**
     * Выравнивает или размещает значение по центру доступной области.
     */
    CENTER,
    /**
     * Выравнивает или размещает значение в конце доступной области.
     */
    END,
    /**
     * Значение {@code SPACE_BETWEEN} задаёт один из режимов перечисления {@code Justify}.
     */
    SPACE_BETWEEN,
    /**
     * Значение {@code SPACE_AROUND} задаёт один из режимов перечисления {@code Justify}.
     */
    SPACE_AROUND,
    /**
     * Значение {@code SPACE_EVENLY} задаёт один из режимов перечисления {@code Justify}.
     */
    SPACE_EVENLY
}
