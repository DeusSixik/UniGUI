package dev.sixik.unigui.editor;

/**
 * Место панели в окне редактора по умолчанию.
 */
public enum PanelSlot {
    /** Центральная область: документы и вьюпорты. Панели одной области складываются во вкладки. */
    CENTER,
    /** Левая колонка: иерархия, палитра. */
    LEFT,
    /** Правая колонка: инспектор. */
    RIGHT,
    /** Нижняя область: проект, консоль, диагностика. */
    BOTTOM
}
